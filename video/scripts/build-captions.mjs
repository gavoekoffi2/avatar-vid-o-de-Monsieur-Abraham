// build-captions.mjs — regenerate the CAP[] block in index.html from a
// Whisper word-level transcript (transcript.json: flat [{text,start,end}]).
//
//   node scripts/build-captions.mjs [transcript.json]
//
// Groups words into 3–5 word phrases (breaks on sentence punctuation, on
// pauses > 0.45s, or at 5 words) and flags money/tax keywords for gold.
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const TRANSCRIPT = process.argv[2] || path.join(root, "transcript.json");
const HTML = path.join(root, "index.html");

// Words to emphasize in gold (normalized, accent-insensitive, matched per token)
const EMPH = [
  "économiser", "économisez", "économies", "centaines", "milliers", "dollars",
  "impôt", "impôts", "énorme", "évitable", "frustrant", "structure",
  "incorporation", "placements", "planification", "fiscale", "fiscal",
  "beaucoup", "légalité", "légal", "consultation",
];

const norm = (s) =>
  s.toLowerCase().normalize("NFD").replace(/[̀-ͯ]/g, "");
const tokens = (s) => norm(s).split(/[^a-z]+/).filter(Boolean);
const emphSet = new Set(EMPH.map((e) => norm(e)));
const isEmph = (t) => tokens(t).some((p) => emphSet.has(p));

let raw = JSON.parse(fs.readFileSync(TRANSCRIPT, "utf8"));
let words = Array.isArray(raw) ? raw : raw.words || (raw.segments || []).flatMap((s) => s.words || []);
words = words
  .map((w) => ({ text: String(w.text ?? w.word ?? "").trim(), start: +w.start, end: +w.end }))
  .filter((w) => w.text && Number.isFinite(w.start) && Number.isFinite(w.end));

if (!words.length) {
  console.error("No words found in transcript:", TRANSCRIPT);
  process.exit(1);
}

const groups = [];
let cur = [];
const flush = () => { if (cur.length) { groups.push(cur); cur = []; } };
for (let i = 0; i < words.length; i++) {
  cur.push(words[i]);
  const endsSentence = /[.?!…]$/.test(words[i].text);
  const next = words[i + 1];
  const pause = next ? next.start - words[i].end : 0;
  if (endsSentence || cur.length >= 5 || pause > 0.45) flush();
}
flush();

const esc = (s) => s.replace(/\\/g, "\\\\").replace(/"/g, '\\"');
const lines = groups.map((g) => {
  const s = g[0].start.toFixed(2);
  const e = g[g.length - 1].end.toFixed(2);
  const arr = g.map((w) => `["${esc(w.text)}",${isEmph(w.text) ? 1 : 0}]`).join(", ");
  return `        G(${s}, ${e}, [${arr}]),`;
}).join("\n");

const block = `/* CAP_START — generated by scripts/build-captions.mjs from transcript.json */
      const CAP = [
${lines}
      ];
      /* CAP_END */`;

let html = fs.readFileSync(HTML, "utf8");
const re = /\/\* CAP_START[\s\S]*?\/\* CAP_END \*\//;
if (!re.test(html)) { console.error("CAP markers not found in index.html"); process.exit(1); }
html = html.replace(re, block);
fs.writeFileSync(HTML, html);

const lastEnd = words[words.length - 1].end;
console.log(`Wrote ${groups.length} caption groups. Last word ends at ${lastEnd.toFixed(2)}s.`);
console.log(`Suggested: TOTAL ≈ ${Math.ceil(lastEnd + 1)}, OUTRO_IN ≈ ${(lastEnd - 4.5).toFixed(1)}.`);
